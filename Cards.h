struct Card
{
    string cardClass;  // ironclad, silent, regent, etc.
    string cardRarity; // common, uncommon, rare, etc.
    string cardType;   // attack, skill, power, etc.
};

struct CardStatistics : Card
{
    int timesPicked = 0;
    int timesSeen   = 0;
    int timesWon    = 0;

    float getPickRate() const
    {
        if (timesSeen == 0) return 0.0f;
        return (float)timesPicked / timesSeen * 100.0f;
    }

    float getWinRate() const
    {
        if (timesPicked == 0) return 0.0f;
        return (float)timesWon / timesPicked * 100.0f;
    }
};

