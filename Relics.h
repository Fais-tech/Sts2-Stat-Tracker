struct Relic
{
    string relicRarity; // common, uncommon, rare, ancient, shop, event
};

struct RelicStatistics : Relic
{
    int timesSeen   = 0;
    int timesPicked = 0;
    int timesWon    = 0;

    float getPickRate() const
    {
        if (timesSeen == 0) return 0.0f;
        return (float)timesPicked / timesSeen * 100.0f;
    }

    float getWinRate() const
    {
        if (timesPicked == 0) return 0.0f;
        return (float)timesWon / timesPicked * 100.0f;
    }
};

